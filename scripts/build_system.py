#!/usr/bin/env python3
"""Render the Full DNS System into ready-to-run files under system/.

Source of truth: data/dns-system.json

For every profile (Kids Guard, Ad Block, Family Safe, Privacy) this writes the
same set of configs with that profile's hostname / DoH URL / IPv4 addresses
filled in:

  system/<profile>/windows-dns.ps1
  system/<profile>/macos-dns.sh
  system/<profile>/systemd-resolved.conf
  system/<profile>/stubby.yml
  system/<profile>/dnsmasq.conf
  system/<profile>/adguardhome-upstreams.txt
  system/<profile>/pihole-upstreams.txt

Plus:

  system/safesearch.conf   SafeSearch CNAME records (Kids Guard / Family Safe)
  system/README.md         Human-readable index

The website renders the exact same templates in the browser, so the copy
button and the committed files always match.

Run:  python scripts/build_system.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "data" / "dns-system.json"
OUT = ROOT / "system"

PLACEHOLDER = re.compile(r"\{\{([A-Z0-9_]+)\}\}")
ALLOWED = {"PROFILE_NAME", "ANDROID_HOST", "DOH_URL", "IPV4", "IPV4_ALT", "DOT_HOST"}


def render(lines: list[str], profile: dict) -> str:
    values = {
        "PROFILE_NAME": profile["name"],
        "ANDROID_HOST": profile["android"],
        "DOH_URL": profile["doh"],
        "IPV4": profile["ipv4"][0],
        "IPV4_ALT": profile["ipv4"][1] if len(profile["ipv4"]) > 1 else profile["ipv4"][0],
        "DOT_HOST": profile["dot_host"],
    }
    text = "\n".join(lines)
    for match in PLACEHOLDER.finditer(text):
        if match.group(1) not in ALLOWED:
            raise SystemExit(f"unknown placeholder {match.group(0)} in profile {profile['id']}")
    return PLACEHOLDER.sub(lambda m: values[m.group(1)], text) + "\n"


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def main() -> None:
    doc = json.loads(SOURCE.read_text(encoding="utf-8"))
    profiles = doc.get("profiles") or []
    configs = doc.get("configs") or {}
    if not profiles or not configs:
        raise SystemExit("dns-system.json has no profiles or configs")

    for profile in profiles:
        for key in ("id", "name", "android", "doh", "ipv4", "dot_host"):
            if not profile.get(key):
                raise SystemExit(f"profile {profile.get('id', '?')} is missing '{key}'")
        if len(profile["ipv4"]) < 2:
            raise SystemExit(f"profile {profile['id']} needs two IPv4 addresses")
        folder = OUT / profile["id"]
        folder.mkdir(parents=True, exist_ok=True)
        # safesearch.conf is profile-independent; it is written once at system/.
        per_profile = {name: lines for name, lines in configs.items() if name != "safesearch.conf"}
        for stale in folder.iterdir():
            if stale.is_file() and stale.name not in per_profile:
                stale.unlink()
        for name, lines in per_profile.items():
            write(folder / name, render(lines, profile))

    # SafeSearch is profile-independent: render it once with the first profile.
    write(OUT / "safesearch.conf", render(configs["safesearch.conf"], profiles[0]))

    rows = "\n".join(
        f"| {p['icon']} {p['name']} | `{p['android']}` | `{p['doh']}` | "
        f"`{p['ipv4'][0]}`, `{p['ipv4'][1]}` | [files]({p['id']}/) |"
        for p in profiles
    )
    readme = f"""# Full DNS System

Generated by [`scripts/build_system.py`](../scripts/build_system.py) from
[`data/dns-system.json`](../data/dns-system.json). Do not edit these files by
hand — edit the JSON and rebuild.

| Profile | Android Private DNS | DoH URL | IPv4 | Configs |
|---|---|---|---|---|
{rows}

## How to use

1. Pick a profile above.
2. Open its folder and use the file for your platform:

| Platform | File |
|---|---|
| Windows 10/11 | `windows-dns.ps1` (run as Administrator) |
| macOS | `macos-dns.sh` (run with `sudo`) |
| Linux (systemd-resolved) | `systemd-resolved.conf` → `/etc/systemd/resolved.conf.d/dns.conf` |
| AdGuard Home | `adguardhome-upstreams.txt` → Settings → DNS settings → Upstream DNS servers |
| Pi-hole | `pihole-upstreams.txt` → Settings → DNS → Upstream DNS servers |
| dnsmasq / OpenWrt | `dnsmasq.conf` (pair with `stubby.yml` for DoT) |
| Stubby | `stubby.yml` → `/etc/stubby/stubby.yml` |

Android, iPhone/iPad and browser-only setups do not need a file: use the
hostname or DoH URL in the table above, or copy the steps from the
**DNS System** tab on the website.

## SafeSearch

[`safesearch.conf`](safesearch.conf) contains the CNAME mappings for Google,
YouTube and Bing SafeSearch. Add them as DNS rewrites in AdGuard Home /
Pi-hole, or as `cname=` lines in dnsmasq 2.86+.

## Notes

- DNS filtering cannot hide a page path. Reels/Shorts need the page-level
  guard from [`guard/shorts-guard.user.js`](../guard/shorts-guard.user.js).
- Every hostname here also appears in [`data/dns-servers.json`](../data/dns-servers.json)
  and passed a live DNS check.
"""
    write(OUT / "README.md", readme)

    files = sum(len([n for n in configs if n != "safesearch.conf"]) for _ in profiles) + 2
    print(f"Wrote {files} files under {OUT.relative_to(ROOT)}/ for {len(profiles)} profiles")


if __name__ == "__main__":
    main()
